#!/usr/bin/env python3
"""23_external_summary.py — regenerate EXTERNAL_VALIDATION_SUMMARY.txt.

The summary used to be written by hand and went stale: it kept reporting the
pre-deduplication cohort (987/743) and the superseded porin figures long after
the tables said 986/742. It is generated from the tables now, so it cannot
disagree with them.

The primary analysis is the whole eligible cohort. No isolate is excluded. One
submission's meropenem calls are taken from the deposited BioSample antibiogram
instead of the aggregated Pathogen Detection field, on the evidence in
results/tables/external_biosample_concordance.tsv, and the uncorrected result is
reported beside it.
"""
import csv
from pathlib import Path

TAB = Path("results/tables")
OUT = Path("results/EXTERNAL_VALIDATION_SUMMARY.txt")


def rows(p):
    with open(p, newline="") as fh:
        return [r for r in csv.DictReader(fh, delimiter="\t")
                if not list(r.values())[0].startswith("#")]


perf = {(r["subset"], r["tier"]): r
        for r in rows(TAB / "external_performance.tsv")}
loo = rows(TAB / "external_leave_one_project_out.tsv")
conc = rows(TAB / "external_biosample_concordance.tsv")
audit = {r["quantity"]: r for r in
         rows(TAB / "external_biosample_audit_summary.tsv")}
snap = Path("data/external/SNAPSHOT.txt")
snapshot = (snap.read_text().strip().splitlines() or ["PDG000000012.2548"])[0] \
    if snap.exists() else "PDG000000012.2548"

full0 = perf[("all_external", "T0_gene_only")]
full2 = perf[("all_external", "T2_family_porin")]
dep0 = perf[("all_external_as_deposited", "T0_gene_only")]
dep2 = perf[("all_external_as_deposited", "T2_family_porin")]

inv = [r for r in conc if r["record_inverted"] == "1"]
sound = [r for r in conc if r["record_inverted"] != "1"]
sound_calls = sum(int(r["n_comparable_calls"]) for r in sound)
sound_conc = sum(int(r["n_concordant"]) for r in sound)
inv_calls = sum(int(r["n_comparable_calls"]) for r in inv)
inv_drugs = max((int(r["n_drugs_compared"]) for r in inv), default=0)
inv_iso = sum(int(r["n_isolates"]) for r in inv)
n_corrected = audit.get(
    "meropenem calls taken from the BioSample record", {}).get("n", "0")

acc = {t: [float(r["accuracy"]) for r in loo if r["tier"] == t]
       for t in ("T0_gene_only", "T2_family_porin")}
n_left_out = len({r["left_out"] for r in loo if float(r["left_out_n"]) > 0})

OUT.write_text(f"""External validation — NCBI Pathogen Detection
Snapshot: {snapshot}
Generated by scripts/23_external_summary.py from results/tables/external_*.tsv.

Eligible external panel, after removing isolates overlapping the derivation set
by assembly or BioSample accession and collapsing one duplicated BioSample:
  {full0['n']} isolates  (PRIMARY external analysis, no isolate excluded)

Record audit against primary sources. Pathogen Detection restates results that
submitters deposited on the BioSample record, so every isolate was checked
against its deposited antibiogram across every drug both sources report:
  {sound_conc} of {sound_calls} calls concordant in {len(sound)} submission(s)
  {inv_calls} calls across {inv_drugs} drugs and {inv_iso} isolates in \
{', '.join(r['bioproject'] for r in inv) or 'no submission'}, none concordant
  {n_corrected} meropenem call(s) taken from the deposited record

Rules fitted on BV-BRC (QC-gated), applied UNCHANGED:
  Primary, phenotype from the primary record ({full0['n']}):
    gene-only  PPV {full0['PPV']}% ({full0['PPV_lo']}-{full0['PPV_hi']})  \
NPV {full0['NPV']}%  acc {full0['accuracy']}% \
({full0['accuracy_lo']}-{full0['accuracy_hi']})
    + porin    PPV {full2['PPV']}% ({full2['PPV_lo']}-{full2['PPV_hi']})  \
NPV {full2['NPV']}%  acc {full2['accuracy']}% \
({full2['accuracy_lo']}-{full2['accuracy_hi']})
  Sensitivity, aggregated calls as deposited, uncorrected ({dep0['n']}):
    gene-only  PPV {dep0['PPV']}%  NPV {dep0['NPV']}%  acc {dep0['accuracy']}%
    + porin    PPV {dep2['PPV']}%  NPV {dep2['NPV']}%  acc {dep2['accuracy']}%

Leave-one-BioProject-out, across the {n_left_out} submissions large enough to
leave out:
  gene-only {min(acc['T0_gene_only']):.1f}-{max(acc['T0_gene_only']):.1f}%\
   + porin {min(acc['T2_family_porin']):.1f}-{max(acc['T2_family_porin']):.1f}%

Reported ampicillin susceptibility was the flag that identified a submission
worth auditing, because K. pneumoniae is intrinsically resistant to ampicillin.
EUCAST treats such a result as an expected-resistant phenotype, meaning at least
90 percent of isolates are expected to be resistant, so the flag warrants
investigation rather than rejection. It excludes nothing here. The finding is
the audit against the deposited records, and only the submission that audit
contradicts was corrected.

Adding porin status within enzyme families improves predictive value here, as it
does under sequence-type-grouped cross-validation in the derivation set.
""")
print(f"[out] {OUT}")
