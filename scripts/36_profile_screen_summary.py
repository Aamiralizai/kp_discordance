#!/usr/bin/env python3
"""36_profile_screen_summary.py — what the profile screen adds to the search.

Asks the question the pairwise search cannot answer on its own. Is there a
protein that a family profile recognises as a beta-lactamase but that no
catalogued allele accounts for?

A profile hit is treated as accounted for when any of three things holds. The
full-length pairwise search named that same protein at or above the identity at
which it names one. Or the genome already carries a catalogued gene of that
family, by the genotype the study is built on, in which case the hit is that
gene or a fragment of it on a contig edge. Or the genome carries a catalogued
gene of that family as a fragment recorded in the fragment table. Anything left
over is the candidate set.

Every Klebsiella genome carries beta-lactamase-fold proteins, so the count of
profile hits means nothing on its own. The control cohort is screened on the
same terms and the comparison between cohorts is the result.

USAGE
    python3 scripts/36_profile_screen_summary.py
"""
import csv
import json
import os
import sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORK = os.path.join(ROOT, "results", "allele_search")
PROFILE = os.path.join(WORK, "profile_hits.jsonl")
PAIRWISE = os.path.join(WORK, "hits.jsonl")
FRAGMENTS = os.path.join(WORK, "fragment_loci.jsonl")
KB = os.path.join(ROOT, "data", "processed",
                  "kleborate_klebsiella_pneumo_complex_output.tsv")
KBP = "klebsiella_pneumo_complex__amr__"
KBCOLS = [KBP + c for c in ("Bla_acquired", "Bla_inhR_acquired",
                            "Bla_ESBL_acquired", "Bla_ESBL_inhR_acquired",
                            "Bla_Carb_acquired", "Bla_chr")]
FAMMETA = os.path.join(WORK, "ref", "betalactamase_families.tsv")
OUT = os.path.join(ROOT, "results", "tables", "profile_screen_summary.tsv")
UNMATCHED = os.path.join(ROOT, "results", "tables",
                         "profile_screen_unmatched_proteins.tsv")

# a profile hit this strong is a confident family assignment rather than a
# fold-level resemblance
STRONG_BITS = 100.0
# the identity at or above which the pairwise search names a protein as the
# catalogued allele or a putative new one, from 33_detection_floor.py
NAMED_IDENTITY = 0.90


def load_jsonl(path):
    out = []
    with open(path) as fh:
        for line in fh:
            line = line.strip()
            if line:
                out.append(json.loads(line))
    return out


def resolve_family(symbol, known):
    """Map a gene symbol such as OXA-48 or CTX-M-15 onto a profile family name.

    Family names in the reference set are inconsistent by design. Some carry an
    allele number and a _fam suffix, as blaOXA-48_fam does, and some are a bare
    stem, as blaCTX-M and blaNDM are. Candidates are generated by dropping
    hyphen-delimited components from the right and the first one that exists is
    taken, so a call is matched to the family it belongs to rather than to a
    prefix it merely shares.
    """
    sym = symbol.strip().lstrip("*^").split("^")[0].split("*")[0]
    sym = sym.split(".")[0]
    if not sym or sym == "-":
        return None
    parts = sym.split("-")
    for k in range(len(parts), 0, -1):
        stem = "-".join(parts[:k])
        for cand in (f"bla{stem}_fam", f"bla{stem}"):
            if cand in known:
                return cand
    return None


def genome_families(known):
    """Beta-lactamase families each genome already carries, by genotype."""
    import re
    out = defaultdict(set)
    with open(KB, newline="", encoding="utf-8", errors="replace") as fh:
        for r in csv.DictReader(fh, delimiter="\t"):
            gid = (r.get("strain") or "").strip()
            if not gid:
                continue
            for col in KBCOLS:
                for g in re.split(r"[;,]", r.get(col, "") or ""):
                    g = g.strip().lstrip("*^").split("^")[0].split("*")[0]
                    if not g or g == "-":
                        continue
                    fam_name = resolve_family(g, known)
                    if fam_name:
                        out[gid].add(fam_name)
    return out


def main():
    prof = load_jsonl(PROFILE)
    pair = load_jsonl(PAIRWISE)
    fam_meta_names = set()
    with open(FAMMETA, encoding="utf-8") as fh:
        cols0 = fh.readline().rstrip("\n").split("\t")
        for line in fh:
            fam_meta_names.add(dict(zip(cols0, line.rstrip("\n").split("\t")))["family"])
    carried = genome_families(fam_meta_names)
    frag = defaultdict(set)
    if os.path.exists(FRAGMENTS):
        for rec in load_jsonl(FRAGMENTS):
            gid = rec.get("genome") or rec.get("genome_id")
            allele = (rec.get("ref") or rec.get("reference_allele") or "")
            allele = allele[3:] if allele.startswith("bla") else allele
            fam_name = resolve_family(allele, fam_meta_names) if allele else None
            if gid and fam_name:
                frag[gid].add(fam_name)
    fam = {}
    with open(FAMMETA, encoding="utf-8") as fh:
        cols = fh.readline().rstrip("\n").split("\t")
        for line in fh:
            v = dict(zip(cols, line.rstrip("\n").split("\t")))
            fam[v["family"]] = v

    # best pairwise identity per (genome, protein)
    best_pair = {}
    for rec in pair:
        for h in rec.get("hits", []):
            k = (rec["genome_id"], h["protein"])
            cur = best_pair.get(k)
            if cur is None or h["identity"] > cur["identity"]:
                best_pair[k] = h

    cohorts = sorted({r["cohort"] for r in prof if "error" not in r})
    rows, unmatched = [], []
    for cohort in cohorts:
        recs = [r for r in prof if r["cohort"] == cohort and "error" not in r]
        n_g = len(recs)
        tot_hits = sum(r["profile_hits"] for r in recs)
        strong = carb_strong = named = unnamed = 0
        unnamed_specific = unnamed_broad = 0
        fam_counter = Counter()
        for r in recs:
            for h in r["hits"]:
                if h["bit_score"] < STRONG_BITS:
                    continue
                strong += 1
                f = fam.get(h["family"], {})
                members = int(f.get("members", 0)) or 1
                carb_frac = int(f.get("carbapenemase_members", 0)) / members
                p = best_pair.get((r["genome_id"], h["protein"]))
                is_named = (
                    (p is not None and p["identity"] >= NAMED_IDENTITY)
                    or h["family"] in carried.get(r["genome_id"], ())
                    or h["family"] in frag.get(r["genome_id"], ())
                )
                fam_counter[h["family"]] += 1
                if carb_frac >= 0.5:
                    carb_strong += 1
                if is_named:
                    named += 1
                else:
                    unnamed += 1
                    if f.get("profile_specific") == "True":
                        unnamed_specific += 1
                    else:
                        unnamed_broad += 1
                    unmatched.append({
                        "cohort": cohort, "genome_id": r["genome_id"],
                        "protein": h["protein"], "aa_length": h["aa_length"],
                        "profile_family": h["family"],
                        "bit_score": h["bit_score"], "evalue": f"{h['evalue']:.2e}",
                        "family_members": f.get("members", ""),
                        "carbapenemase_members": f.get("carbapenemase_members", ""),
                        "dominant_subclass": f.get("dominant_subclass", ""),
                        "profile_specific": f.get("profile_specific", ""),
                        "member_length_ratio": f.get("member_length_ratio", ""),
                        "best_pairwise_symbol": p["ref_symbol"] if p else "",
                        "best_pairwise_identity": p["identity"] if p else "",
                        "best_pairwise_coverage": p["ref_coverage"] if p else "",
                    })
        rows.append({
            "cohort": cohort, "genomes": n_g,
            "profile_hits_any": tot_hits,
            "profile_hits_per_genome": round(tot_hits / n_g, 2) if n_g else "",
            f"strong_hits_bits_ge_{int(STRONG_BITS)}": strong,
            "strong_per_genome": round(strong / n_g, 2) if n_g else "",
            "strong_in_carbapenemase_family": carb_strong,
            "strong_named_by_pairwise": named,
            "strong_not_named_by_pairwise": unnamed,
            # split by whether the profile that produced the hit is specific to
            # one enzyme family. A hit from a broad profile is a fold match, not
            # a candidate enzyme.
            "not_named_specific_profile": unnamed_specific,
            "not_named_specific_per_genome": (round(unnamed_specific / n_g, 3)
                                             if n_g else ""),
            "not_named_broad_profile": unnamed_broad,
            "top_families": "; ".join(f"{k} {v}" for k, v in
                                      fam_counter.most_common(6)),
        })

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]), delimiter="\t")
        w.writeheader()
        w.writerows(rows)
    with open(UNMATCHED, "w", newline="", encoding="utf-8") as fh:
        cols = ["cohort", "genome_id", "protein", "aa_length", "profile_family",
                "bit_score", "evalue", "family_members", "carbapenemase_members",
                "dominant_subclass", "profile_specific", "member_length_ratio",
                "best_pairwise_symbol",
                "best_pairwise_identity", "best_pairwise_coverage"]
        w = csv.DictWriter(fh, fieldnames=cols, delimiter="\t")
        w.writeheader()
        w.writerows(sorted(unmatched, key=lambda r: -r["bit_score"]))

    for r in rows:
        print(f"  {r['cohort']:24s} genomes {r['genomes']:4d}  "
              f"strong {r[f'strong_hits_bits_ge_{int(STRONG_BITS)}']:4d} "
              f"({r['strong_per_genome']}/genome)  "
              f"named {r['strong_named_by_pairwise']:4d}  "
              f"not named {r['strong_not_named_by_pairwise']:4d}")
    print(f"\n  strongest profile hits with no catalogued allele above "
          f"{NAMED_IDENTITY:.0%} identity:")
    for u in sorted(unmatched, key=lambda r: -r["bit_score"])[:12]:
        print(f"    {u['cohort']:22s} {u['genome_id']:12s} {u['protein']:10s} "
              f"{u['profile_family']:16s} bits {u['bit_score']:7.1f}  "
              f"nearest {u['best_pairwise_symbol'] or '-'} "
              f"id {u['best_pairwise_identity'] or '-'}")
    print(f"\n[out] {OUT}")
    print(f"[out] {UNMATCHED}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
